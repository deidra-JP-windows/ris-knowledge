def main():
    """各部門に対して、来期の所属人数から今期の所属人数を引いた値を求める
    処理概要:
        1. 社員の数 N と部門の数 M を入力する。
        2. 各社員の今期所属部門 A_i と来期所属部門 B_i を入力する。
          - AとBはそれぞれ配列に格納する。
        3. 各部門に対して、来期の所属人数から今期の所属人数を引いた値を計算する。
        4. 計算結果を出力する。
    補足：
        1.
    前提:
        1. 
    条件:
        1. 各社員には 1,2,…,N の社員番号が割り当てられる
        2. 各部門には 1,2,…,M の部門番号が割り当てられる
        3. 社員番号 i の社員は、今期は部門 A_i に所属しており、来期は部門 B_i に所属する
    制約:
        1. 1≤N≤100
        2. 1≤M≤100
        3. 1≤A_i≤M
        4. 1≤B_i≤M
        5. N,M,A_i,B_i はすべて整数
    Args:
        None
    Inputs:
        N (int): 社員の数
        M (int): 部門の数
        A (int): 社員番号 i の社員が今期所属している部門番号 A_i
        B (int): 社員番号 i の社員が来期所属している部門番号 B_i
    Prints:
        str: 各部門に対して、来期の所属人数から今期の所属人数を引いた値を改行区切りで出力する
          - 1 行目には部門 1 に対する値を、2 行目には部門 2 に対する値を、…、M 行目には部門 M に対する値を出力する
    Returns:
        None
    """
    # 社員の数 N と部門の数 M を入力する。
    N, M = map(int, input().split())
    # 各社員の今期所属部門 A_i と来期所属部門 B_i を入力する。
    A = []
    B = []
    for _ in range(N):
        A_i, B_i = map(int, input().split())
        A.append(A_i)
        B.append(B_i)
    # 各部門に対して、来期の所属人数から今期の所属人数を引いた値を計算する。
    result = []
    for i in range(1, M + 1):
        count_A = A.count(i)
        count_B = B.count(i)
        result.append(count_B - count_A)
    # 計算結果を出力する。
    for r in result:
        print(r)


# ローカル実行
if __name__ == "__main__":
    main()
