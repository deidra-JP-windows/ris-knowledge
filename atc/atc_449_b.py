def main():
    """
    処理概要:
        1. 長方形のチョコレートを表す行列H,Wとクエリ数である Q を入力として受け取る
        2. クエリを順に処理したときの各クエリの答えを順に出力するためのリストを初期化する
        2. クエリの数だけ以下を処理する
            1. クエリの内容を入力として受け取る
            2. クエリの内容に応じて、以下のいずれかの処理を行う
               1. タイプ 1 のクエリの場合、下 R 行のチョコレートのブロックの個数を求め、それらを食べる
               2. タイプ 2 のクエリの場合、右 C 列のチョコレートのブロックの個数を求め、それらを食べる
        3. クエリを順に処理したときの各クエリの答えを順に出力する
    補足：
        1. クエリを順に処理する
    前提:
        1. H 行 W 列のブロックからなる長方形状のチョコレート
        2. Q 個のクエリが与えられる
        3. 順に処理したときの各クエリの答えを求める
        4. 各クエリは、以下のいずれかの形式で与えられる
           1. 整数 R が与えられる。下 R 行のチョコレートのブロックの個数を求め、それらを食べる。
           2. 整数 C が与えられる。右 C 列のチョコレートのブロックの個数を求め、それらを食べる。
    条件:
        1. クエリを順に処理したとき、各クエリを処理した後もチョコレートは長方形状
    制約:
        1. 2≤H,W≤100
        2. 1≤Q≤100
        3. 入力される値はすべて整数
        4. タイプ 1 のクエリを処理する直前の時点でチョコレートは R+1 行以上存在
        5. タイプ 2 のクエリを処理する直前の時点でチョコレートは C+1 列以上存在
    Args:
        None
    Inputs:
        H (int): チョコレートの行数
        W (int): チョコレートの列数
        Q (int): クエリの数
        query (list of str): クエリの内容を表す文字列のリスト
          - タイプ 1 のクエリは "1" の形式で与えられる。R は整数で、下 R 行のチョコレートのブロックの個数を求める。
          - タイプ 2 のクエリは "2" の形式で与えられる。C は整数で、右 C 列のチョコレートのブロックの個数を求める。
          - 例: "1 2" はタイプ 1 のクエリで、下 2 行のチョコレートのブロックの個数を求める。 "2 3" はタイプ 2 のクエリで、右 3 列のチョコレートのブロックの個数を求める。
    Prints:
        str: 各クエリの答えである行or列を順に出力する。
    Returns:
        None
    """
    # 長方形のチョコレートを表す行列H,Wとクエリ数である Q を入力として受け取る
    H, W, Q = map(int, input().split())
    # クエリを順に処理したときの各クエリの答えを順に出力するためのリストを初期化する
    results = []
    # クエリの数だけ以下を処理する
    for _ in range(Q):
        # クエリの内容を入力として受け取る
        query = input().split()
        # クエリの内容に応じて、以下のいずれかの処理を行う
        if query[0] == "1":
            # タイプ 1 のクエリの場合、下 R 行のチョコレートのブロックの個数を求め、それらを食べる
            R = int(query[1])
            results.append(str(R * W))
            H -= R
        elif query[0] == "2":
            # タイプ 2 のクエリの場合、右 C 列のチョコレートのブロックの個数を求め、それらを食べる
            C = int(query[1])
            results.append(str(C * H))
            W -= C
    # クエリを順に処理したときの各クエリの答えを順に出力する
    print("\n".join(results))


# ローカル実行
if __name__ == "__main__":
    main()
