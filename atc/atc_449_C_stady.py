import sys


def main() -> None:
    """
    処理概要:
        1. 文字列長 n、距離下限 l、距離上限 r、文字列 s を入力として受け取る
        2. 各位置 i について、過去位置 j のうち距離条件 l <= i-j <= r を満たす範囲を管理する
        3. その範囲内で s[i] と同じ文字の個数を加算し、条件を満たすペア総数を求める
        4. 最終的な総数を出力する

    前提:
        1. s は英小文字（'a'〜'z'）で構成される
        2. 入力は n, l, r と長さ n の文字列 s

    条件:
        1. ペア (j, i) は j < i
        2. 距離条件は l <= i-j <= r
        3. 文字条件は s[j] == s[i]

    主要変数（引数・役割）:
        n (int): 文字列 s の長さ
        l (int): インデックス距離 i-j の下限
        r (int): インデックス距離 i-j の上限
        s (str): 対象文字列
        ans (int): 条件を満たすペア数の累積
        cnt (list[int]): 現在有効な過去位置の文字頻度（a〜z の 26 要素）
    """
    # 高速入力を使うために input を差し替える
    input = sys.stdin.readline

    # n: 文字列長, l: 距離下限, r: 距離上限
    n, l, r = map(int, input().split())
    # 対象文字列
    s = input().strip()

    # 区間を半開区間的に扱いやすくするため r を 1 増やす
    # これにより「i >= r なら削除」という形で管理できる
    # インクルードからエクスクルードに変えるための調整
    r += 1

    # 答え（有効ペア数の合計）
    ans = 0
    # 各文字の出現回数を管理する配列（0: 'a', ..., 25: 'z'）
    cnt = [0] * 26

    # i を右端として 0 から順に見る
    for i in range(n):
        # i-l が新たに有効範囲に入るので、その文字を追加
        if i >= l:
            cnt[ord(s[i - l]) - ord('a')] += 1

        # i-r が有効範囲から外れるので、その文字を削除
        if i >= r:
            cnt[ord(s[i - r]) - ord('a')] -= 1

        # 現在文字 s[i] と同じ文字が有効範囲内に何個あるかを加算
        ans += cnt[ord(s[i]) - ord('a')]

    # 総ペア数を出力
    print(ans)


# 直接実行されたときのみ main を呼ぶ
if __name__ == "__main__":
    main()