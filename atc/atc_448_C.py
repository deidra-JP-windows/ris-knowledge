def main():
    """袋に入っているボールに書かれた整数の最小値を求める
    処理概要:
        1. 整数 N と Q を半角スペース区切りで入力する
        2. ボール i に書かれる整数 Ai を半角スペース区切りで入力する
        3. (値, ボール番号) のペアを作成し、値でソートする O(N log N)
        4. Q 個のクエリに対して以下を実行
            - Ai が書かれたボールの番号である B の長さ K を入力する
            - Ai が書かれたボールの番号である B を半角スペース区切りで入力する
            - ソート済みの最初の6個から削除されていないボールを探す O(1)
            - 削除されていないボールの最小値を出力する
    補足：
        1. K ≤ 5 のため、最悪でも5個削除されても6個目のボールは必ず残る
        2. 事前ソートにより、各クエリは O(1) で処理可能
        3. boals (list of tuple): (値, ボール番号) のペア。値でソート済み
    前提:
        1. ボール i には整数 Ai が書いてある
        2. N個のボールには 1 から N までの番号がついている
        3. クエリでは長さ K の数列 B1,B2,…,BKが与えられる
    条件:
        1. 実行時間は O(N log N + Q) でなければならない
          - O(Q * N) はタイムアウトする
          - 事前ソート: O(N log N)
          - クエリ処理: O(Q) (各クエリは最大6個チェックで O(1))
    制約:
        1. 6 ≤ N ≤ 3 * 10^5
        2. 1 ≤ Q ≤ 2 * 10^5
        3. 1 ≤ Ai ≤ 10^9
        4. 1 ≤ K ≤ 5
        5. 1 ≤ B1 < B2 <⋯< BK ≤ N
        6. 全てのクエリに対する K の総和は 4 * 10^5 以下
        7. 入力される値は全て整数
    Args:
        None
    Inputs:
        N (int): ボールの数
        A (list of int): ボール i に書かれる整数 Ai
        Q (int): クエリの数
        K (int): 削除するボールの番号である数列 B の長さ
        B (set of int): 削除するボールの番号
    Prints:
        int: 各クエリ後の袋に入っているボールの最小値（Q行出力） 
    Returns:
        None
    """
    # 整数 N と Q を半角スペース区切りで入力する
    N, Q = map(int, input().split())
    # ボール i に書かれる整数 Ai を半角スペース区切りで入力する
    A = list(map(int, input().split()))
    
    # (値, ボール番号) のペアを作成して値でソート
    # インデックス i は 0-indexed なので、ボール番号は i+1
    boal_tuple = [(x, i+1) for i, x in enumerate(A)]
    boal_tuple.sort(key=lambda x: x[0])  # 値の昇順でソート O(N log N)
    
    # Q 個のクエリに対して以下を実行
    for _ in range(Q):
        # Ai が書かれたボールの番号である B の長さ K を入力する
        K = int(input())
        # Ai が書かれたボールの番号である B を半角スペース区切りで入力する
        B = set(map(int, input().split()))
        
        # 値が小さい順に最初の6個から削除されていないボールを探す
        # K ≤ 5 なので、最悪でも5個削除されても6個目は必ず残る
        for i in range(6):
            # boal_tuple[i][0]: ボールの値, boal_tuple[i][1]: ボール番号
            if boal_tuple[i][1] not in B:
                # 削除されていないボールの値を出力
                print(boal_tuple[i][0])
                break

        
# ローカル実行
if __name__ == "__main__":
    main()
